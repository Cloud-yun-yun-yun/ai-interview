  "skill_match_score" int4 NOT NULL,
  "content_score" int4 NOT NULL,
  "structure_score" int4 NOT NULL,
  "expression_score" int4 NOT NULL,
  "summary" text COLLATE "pg_catalog"."default",
  "suggestions" text COLLATE "pg_catalog"."default",
