  "session_status" COLLATE "pg_catalog"."default" "pg_catalog"."text_ops" ASC NULLS LAST
);
ALTER TABLE "interview_session" ADD CONSTRAINT "uk_interview_session_request_id" UNIQUE ("request_id");
ALTER TABLE "interview_session" ADD CONSTRAINT "interview_session_status_check" CHECK (session_status::text = ANY (ARRAY['CREATED'::character varying, 'SUBMITTED'::character varying, 'EVALUATED'::character varying]::text[]));
ALTER TABLE "interview_session" ADD CONSTRAINT "interview_session_pkey" PRIMARY KEY ("session_id");

-- knowledge_base_question
CREATE INDEX "idx_kb_question_kb_id" ON "knowledge_base_question" USING btree (
  "kb_id" "pg_catalog"."int8_ops" ASC NULLS LAST
