
/*
 ============================================================================
  interview 库 —— 一键建表结构脚本（Navicat 查询窗口可直接执行，无数据）
  用法：先在 Navicat 里手动建好库（右键连接 -> 新建数据库 -> interview），
        双击打开该库 -> 新建查询 -> 粘贴本脚本 -> 点「运行」即可。
  说明：Navicat 查询窗口走数据库连接协议，不认 \connect 这类 psql 元命令，
        且 CREATE DATABASE 不能包在事务里，故本脚本不建库、只建表。
        表会建在你「当前打开查询窗口所选中」的那个库里，执行前确认库选对。
  适配镜像：pgvector/pgvector:pg16（vector(1024) 类型 + hnsw 索引需 pgvector）
  重复执行：扩展/序列带 IF NOT EXISTS；建表为 DROP + CREATE，重跑会清空重建。
 ============================================================================
*/

-- ===================== 1. 扩展（必须在目标库内、建表前执行） =====================
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";   -- vector_qa 用 uuid_generate_v4()
CREATE EXTENSION IF NOT EXISTS "vector";      -- vector(1024) 类型 + hnsw 索引

-- ===================== 2. 序列（建表 DEFAULT nextval 依赖） =====================
CREATE SEQUENCE IF NOT EXISTS interview_question_id_seq;
CREATE SEQUENCE IF NOT EXISTS knowledge_bases_id_seq;
CREATE SEQUENCE IF NOT EXISTS resume_id_seq;
CREATE SEQUENCE IF NOT EXISTS user_id_seq;
CREATE SEQUENCE IF NOT EXISTS voice_interview_turn_id_seq;

-- ===================== 3. 建表 =====================

DROP TABLE IF EXISTS "interview_question";
CREATE TABLE "interview_question" (
  "id" int4 NOT NULL DEFAULT nextval('interview_question_id_seq'::regclass),
  "session_id" varchar(255) COLLATE "pg_catalog"."default" NOT NULL,
  "question_index" int4 NOT NULL,
  "question_content" text COLLATE "pg_catalog"."default",
  "topic_summary" text COLLATE "pg_catalog"."default",
  "type" varchar(64) COLLATE "pg_catalog"."default",
  "user_answer" text COLLATE "pg_catalog"."default",
  "scoring_rubric" text COLLATE "pg_catalog"."default",
  "reference_answer" text COLLATE "pg_catalog"."default"
);

DROP TABLE IF EXISTS "interview_session";
CREATE TABLE "interview_session" (
  "session_id" varchar(36) COLLATE "pg_catalog"."default" NOT NULL,
  "session_status" varchar(20) COLLATE "pg_catalog"."default" NOT NULL DEFAULT 'CREATED'::character varying,
  "user_id" int8,
  "total_questions" int4,
  "total_score" int4,
  "feedback" text COLLATE "pg_catalog"."default",
  "resume_id" int8,
  "request_id" varchar(64) COLLATE "pg_catalog"."default",
  "kb_id" int8,
  "session_evaluate_status" varchar(20) COLLATE "pg_catalog"."default",
  "current_index" int4 DEFAULT 0,
  "session_questiongen_status" varchar(20) COLLATE "pg_catalog"."default" DEFAULT 'GENERATING'::character varying,
  "session_name" varchar(128) COLLATE "pg_catalog"."default" DEFAULT '未命名面试'::character varying,
  "create_time" timestamp(6),
  "async_task_updated_at" timestamp(6)
);
COMMENT ON COLUMN "interview_session"."session_status" IS '会话整体状态 (如 CREATED, EVALUATING, SUBMITTED, COMPLETED 等)';
COMMENT ON COLUMN "interview_session"."request_id" IS '前端生成的 UUID，用于防止重复提交（幂等性控制）';
COMMENT ON COLUMN "interview_session"."kb_id" IS '关联的知识库 ID（可为空）';

DROP TABLE IF EXISTS "knowledge_base_question";
CREATE TABLE "knowledge_base_question" (
  "id" int8 NOT NULL GENERATED BY DEFAULT AS IDENTITY (
INCREMENT 1
MINVALUE  1
MAXVALUE 9223372036854775807
START 1
CACHE 1
),
  "type" varchar(64) COLLATE "pg_catalog"."default",
  "question" text COLLATE "pg_catalog"."default" NOT NULL,
  "topic_summary" varchar(300) COLLATE "pg_catalog"."default",
  "reference_answer" text COLLATE "pg_catalog"."default",
  "scoring_rubric" text COLLATE "pg_catalog"."default",
  "kb_id" int8
);
COMMENT ON COLUMN "knowledge_base_question"."type" IS '题目类型（如 技术题 / 场景题 / 设计题）';
COMMENT ON COLUMN "knowledge_base_question"."question" IS '题干预设为 NOT NULL';
COMMENT ON COLUMN "knowledge_base_question"."topic_summary" IS '该题覆盖的知识点摘要';
COMMENT ON COLUMN "knowledge_base_question"."reference_answer" IS '参考答案';
COMMENT ON COLUMN "knowledge_base_question"."scoring_rubric" IS '评分标准';
COMMENT ON COLUMN "knowledge_base_question"."kb_id" IS '关联的知识库 ID';
COMMENT ON TABLE "knowledge_base_question" IS '知识库题目表';

DROP TABLE IF EXISTS "knowledge_bases";
CREATE TABLE "knowledge_bases" (
  "id" int8 NOT NULL DEFAULT nextval('knowledge_bases_id_seq'::regclass),
  "file_hash" varchar(64) COLLATE "pg_catalog"."default" NOT NULL,
  "name" varchar(255) COLLATE "pg_catalog"."default" NOT NULL,
  "original_filename" varchar(255) COLLATE "pg_catalog"."default" NOT NULL,
  "file_size" int8,
  "content_type" varchar(255) COLLATE "pg_catalog"."default",
  "storage_key" varchar(500) COLLATE "pg_catalog"."default",
  "uploaded_at" timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "vector_status" varchar(20) COLLATE "pg_catalog"."default" DEFAULT 'PENDING'::character varying,
  "chunk_count" int4 DEFAULT 0,
  "question_gen_status" varchar(20) COLLATE "pg_catalog"."default" DEFAULT 'NONE'::character varying,
  "question_gen_task_id" varchar(255) COLLATE "pg_catalog"."default",
  "question_gen_updated_at" timestamp(6),
  "user_id" int8,
  "vector_status_updated_at" timestamp(6) DEFAULT NULL::timestamp with time zone
);
COMMENT ON COLUMN "knowledge_bases"."id" IS '主键';
COMMENT ON COLUMN "knowledge_bases"."file_hash" IS '文件内容的 SHA-256 哈希值，用于去重';
COMMENT ON COLUMN "knowledge_bases"."name" IS '知识库名称（用户自定义或从文件名提取）';
COMMENT ON COLUMN "knowledge_bases"."original_filename" IS '原始文件名';
COMMENT ON COLUMN "knowledge_bases"."file_size" IS '文件大小（字节）';
COMMENT ON COLUMN "knowledge_bases"."content_type" IS '文件类型';
COMMENT ON COLUMN "knowledge_bases"."storage_key" IS 'RustFS 存储的文件 Key';
COMMENT ON COLUMN "knowledge_bases"."uploaded_at" IS '上传时间';
COMMENT ON COLUMN "knowledge_bases"."vector_status" IS '向量化状态：PENDING/PROCESSING/COMPLETED/FAILED';
COMMENT ON COLUMN "knowledge_bases"."chunk_count" IS '向量分块数量';
COMMENT ON COLUMN "knowledge_bases"."question_gen_status" IS '问题生成状态：NONE/PENDING/PROCESSING/COMPLETED/FAILED';
COMMENT ON COLUMN "knowledge_bases"."vector_status_updated_at" IS '向量化状态(vector_status)最后一次更新时间';
COMMENT ON TABLE "knowledge_bases" IS '知识库';

DROP TABLE IF EXISTS "resume";
CREATE TABLE "resume" (
  "id" int8 NOT NULL DEFAULT nextval('resume_id_seq'::regclass),
  "user_id" int8 NOT NULL,
  "async_task_status" varchar(20) COLLATE "pg_catalog"."default" NOT NULL DEFAULT '0'::character varying,
  "content" text COLLATE "pg_catalog"."default",
  "text_length" int4,
  "file_hash" varchar(64) COLLATE "pg_catalog"."default",
  "name" varchar(50) COLLATE "pg_catalog"."default",
  "interview_status" varchar(50) COLLATE "pg_catalog"."default"
);

DROP TABLE IF EXISTS "resume_analysis_response";
CREATE TABLE "resume_analysis_response" (
  "id" int8 NOT NULL GENERATED BY DEFAULT AS IDENTITY (
INCREMENT 1
